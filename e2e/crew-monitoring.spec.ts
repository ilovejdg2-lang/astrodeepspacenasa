import { expect, test } from '@playwright/test'

test.use({ channel: process.env.PLAYWRIGHT_CHANNEL as 'chrome' | undefined })

test('mission overview links to crew records and preserves selection on reload', async ({ page }) => {
  await page.route('**/api/nasa/**', (route) => route.fulfill({ status: 503, json: { message: 'Unavailable' } }))
  await page.goto('/entrar')
  await page.getByRole('button', { name: 'ES', exact: true }).click()
  await page.getByRole('button', { name: 'Explorar como jefe', exact: true }).click()
  await page.getByRole('button', { name: 'Entrar al tablero', exact: true }).first().click()
  await page.goto('/app/centro')
  await expect(page.getByRole('heading', { level: 1, name: 'Centro de misión' })).toBeVisible()
  await expect(page.locator('.monitor-card')).toHaveCount(0)
  await expect(page.locator('.mission-crew-card')).toHaveCount(4)
  await page.getByTestId('view-monitoring-mateo-ruiz').click()
  await expect(page).toHaveURL(/tripulacion\/mateo-ruiz$/)
  await expect(page.getByRole('heading', { level: 1, name: 'Mateo Ruiz' })).toBeVisible()
  await expect(page.locator('.monitor-card')).toBeVisible()
  await page.getByTestId('crew-alex-morgan').click()
  await expect(page).toHaveURL(/tripulacion\/alex-morgan$/)
  await page.reload()
  await expect(page.getByRole('heading', { level: 1, name: 'Alex Morgan' })).toBeVisible()
  await page.getByRole('link', { name: /Volver a tripulaci/ }).click()
  await expect(page).toHaveURL(/tripulacion$/)
  await page.getByTestId('crew-profile-mateo-ruiz').click()
  await expect(page.getByRole('heading', { level: 1, name: 'Mateo Ruiz' })).toBeVisible()
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(page.locator('.monitor-card')).toBeVisible()
  await page.screenshot({ path: 'test-results/crew-monitor-mobile.png' })
})

import AxeBuilder from '@axe-core/playwright'
import { expect, test } from '@playwright/test'

test('recorre el flujo principal con datos compartidos', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByText('Simulación · datos ficticios')).toBeVisible()
  await page.getByTestId('theme-light').click()
  await page.reload()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
  await page.getByTestId('theme-dark').click()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')

  await page.getByTestId('crew-mateo-ruiz').click()
  await expect(page.getByRole('heading', { level: 1, name: 'Mateo Ruiz' })).toBeVisible()
  await page.getByTestId('crew-elena-torres').click()
  await page.getByTestId('open-symptom').click()
  await page.getByTestId('save-symptom').click()
  await expect(page.getByText('Indicá al menos un síntoma o una nota.')).toBeVisible()
  await page.getByTestId('symptom-cansancio').check()
  await page.getByTestId('symptom-note').fill('Cansancio al moverme por el módulo.')
  await page.getByTestId('save-symptom').click()
  await expect(page.getByText('Cansancio al moverme por el módulo.')).toBeVisible()

  await page.getByRole('link', { name: 'Historial' }).click()
  await expect(page.getByRole('listitem').filter({ hasText: 'Cansancio al moverme por el módulo.' }).first()).toBeVisible()

  await page.getByRole('link', { name: 'Alertas' }).click()
  await expect(page.getByRole('heading', { name: 'Centro de alertas' })).toBeVisible()
  await page.getByRole('button', { name: /Cambio en signos/ }).click()
  await page.getByRole('link', { name: 'Abrir análisis' }).click()
  await expect(page.getByTestId('analysis-local')).toContainText('Motor de análisis simulado')
  await expect(page.getByTestId('analysis-local')).not.toContainText('diagnóstico confirmado')

  await page.getByRole('link', { name: 'Recursos' }).click()
  await page.getByTestId('resource-oximeter').getByRole('button', { name: 'Oxímetro' }).click()
  await page.getByTestId('open-use').click()
  await page.getByTestId('use-quantity').fill('0')
  await page.getByTestId('save-use').click()
  await expect(page.getByText('Indicá un entero mayor que cero.')).toBeVisible()
  await page.getByTestId('use-quantity').fill('1')
  await page.getByTestId('save-use').click()
  await expect(page.getByTestId('notice')).toContainText('Uso de equipo reutilizable')
  await expect(page.getByText('Uso · Oxímetro')).toBeVisible()
  await expect(page.getByTestId('resource-oximeter')).toContainText('2')

  await page.getByTestId('link-toggle').click()
  await expect(page.getByText('Enlace Tierra: sin conexión')).toBeVisible()
  await page.getByRole('link', { name: 'Equipo médico' }).click()
  await page.getByTestId('comm-subject').fill('Resumen de Elena')
  await page.getByTestId('comm-body').fill('Se observó un cambio. Se pide revisión humana.')
  await page.getByTestId('save-draft').click()
  await expect(page.getByTestId('notice')).toContainText('Borrador guardado')
  await page.getByTestId('queue-comm').click()
  await expect(page.getByTestId('notice')).toContainText('El mensaje quedó en cola')
  await expect(page.getByTestId('deliver-comm')).toBeDisabled()
  await expect(page.getByText('El enlace está cortado')).toBeVisible()
  await expect(page.getByRole('cell', { name: 'En cola' })).toBeVisible()

  await page.getByTestId('link-toggle').click()
  await page.getByTestId('deliver-comm').click()
  await page.getByTestId('deliver-comm').click()
  await expect(page.getByRole('cell', { name: 'Enviado', exact: true })).toBeVisible()
  await expect(page.getByRole('cell', { name: 'Recibido', exact: true })).toHaveCount(0)
  await page.getByTestId('confirm-comm').click()
  await page.getByTestId('confirm-comm').click()
  await expect(page.getByRole('cell', { name: 'Recibido', exact: true })).toHaveCount(1)

  await page.getByTestId('sim-play').click()
  await page.getByTestId('sim-pause').click()
  await page.getByTestId('sim-reset').click()
  await page.getByTestId('confirm-reset').click()
  await expect(page.getByText('Cansancio al moverme por el módulo.')).toHaveCount(0)
})

test('la pantalla principal no tiene violaciones críticas de accesibilidad', async ({ page }) => {
  await page.goto('/')
  const results = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa']).analyze()
  const serious = results.violations.filter((item) => item.impact === 'serious' || item.impact === 'critical')
  expect(serious.map((item) => item.id)).toEqual([])
})
